#!/usr/bin/env python3
"""Follow-up #2's full test: SFT on train + the proposed global prompts against
the 100% scaling point, judged as pre-registered
(runs/followups_2026-10-16/preregistration.md, addendum).

    primary    global rows of test v2 together with the global rows among the 295
               untouched val rows, paired, exact McNemar
    secondary  all of test v2 + the untouched val rows; T3; per category

    python scripts/global_additions/compare.py --base runs/qwen3.5-4b-sft-ds100 \\
        --new runs/qwen3.5-4b-sft-plusglobal --out runs/global_additions_2026-10-16/report.md
"""
import argparse
import collections
import json
import math
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "scripts"))


def load_jsonl(path):
    with open(path, encoding="utf-8") as fh:
        return [json.loads(l) for l in fh if l.strip()]


def mcnemar_p(g, l):
    n = g + l
    if n == 0:
        return 1.0
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(min(g, l) + 1)) / 2 ** n)


def paired(base, new, ids):
    ids = [i for i in ids if i in base and i in new]
    g = sum(1 for i in ids if new[i] and not base[i])
    l = sum(1 for i in ids if base[i] and not new[i])
    b = sum(base[i] for i in ids)
    n_ = sum(new[i] for i in ids)
    return {"n": len(ids), "base": 100 * b / len(ids) if ids else float("nan"),
            "new": 100 * n_ / len(ids) if ids else float("nan"),
            "delta": 100 * (n_ - b) / len(ids) if ids else float("nan"), "gained": g, "lost": l,
            "p": mcnemar_p(g, l)}


def row(name, r):
    return "| %s | %d | %.1f%% | %.1f%% | %+.1f | +%d / −%d | %.3f |" % (
        name, r["n"], r["base"], r["new"], r["delta"], r["gained"], r["lost"], r["p"])


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--base", required=True)
    ap.add_argument("--new", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--json", default=None)
    args = ap.parse_args(argv)
    from train_sft import SUBSET_SEED, stratified_subset
    test = {c["id"]: c for c in load_jsonl(REPO / "data" / "splits" / "test.jsonl")}
    val = load_jsonl(REPO / "data" / "splits" / "val.jsonl")
    sel = {c["id"] for c in stratified_subset(val, 250, seed=SUBSET_SEED)}
    untouched = {c["id"]: c for c in val if c["id"] not in sel}
    pool = dict(test)
    pool.update(untouched)

    def ex(run, split):
        return {r["id"]: bool(r["match"]) for r in load_jsonl(pathlib.Path(run) / ("exec_%s.jsonl" % split))}
    base = dict(ex(args.base, "test"))
    base.update({k: v for k, v in ex(args.base, "val").items() if k in untouched})
    new = dict(ex(args.new, "test"))
    new.update({k: v for k, v in ex(args.new, "val").items() if k in untouched})
    glob = [i for i, c in pool.items() if c.get("category") == "global"]
    res = {"primary: global rows, test v2 + untouched val": paired(base, new, glob),
           "global rows, test v2 only": paired(base, new, [i for i in glob if i in test]),
           "all rows, test v2 + untouched val": paired(base, new, list(pool)),
           "all rows, test v2 only": paired(base, new, list(test)),
           "T3 rows, test v2 + untouched val": paired(base, new, [i for i, c in pool.items() if c.get("tier") == "T3"]),
           "non-global rows, test v2 + untouched val": paired(base, new, [i for i, c in pool.items() if c.get("category") != "global"])}
    L = ["# Follow-up #2: SFT with the proposed global prompts, the full test", "",
         "Generated by `scripts/global_additions/compare.py`. Base: `%s` (train only). New: `%s` "
         "(train + the %d proposed global prompts, unreviewed). Same recipe, stack and seed; both scored "
         "greedily on test v2 and full val. Rules: `runs/followups_2026-10-16/preregistration.md` (addendum)." % (
             args.base, args.new, sum(1 for _ in open(REPO / "data" / "proposed" / "global_2026-10-16" / "cases.jsonl"))), "",
         "| slice | rows | train only | + global prompts | Δ | gained / lost | exact McNemar p |",
         "|---|---|---|---|---|---|---|"]
    for name, r in res.items():
        L.append(row(name, r))
    L += ["", "Expectations stated in advance: about +10 on the global rows if the new prompts are worth what "
          "existing rows are (the global scaling slope, +12 per doubling, at +75% global train rows), and about "
          "+2.7 overall, which the 724-row pool cannot resolve (its detection limit is about 4.7 points).", "",
          "## Per category (test v2 + untouched val)", "",
          "| category | rows | train only | + global prompts | Δ |", "|---|---|---|---|---|"]
    cats = collections.Counter(c.get("category") for c in pool.values())
    for cat, n in cats.most_common():
        r = paired(base, new, [i for i, c in pool.items() if c.get("category") == cat])
        L.append("| %s | %d | %.1f%% | %.1f%% | %+.1f |" % (cat, r["n"], r["base"], r["new"], r["delta"]))
    L.append("")
    pathlib.Path(args.out).write_text("\n".join(L), encoding="utf-8")
    if args.json:
        pathlib.Path(args.json).write_text(json.dumps(res, indent=1) + "\n", encoding="utf-8")
    print("report -> %s" % args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
